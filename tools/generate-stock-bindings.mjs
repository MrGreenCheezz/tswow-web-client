import { existsSync, readdirSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { interfaceDirectory, sourceClientDirectory } from "./paths.mjs";

/**
 * Emits the tracked `src/generated/stockBindings.ts`: which binding commands the 3.3.5a client
 * (build 12340) knows and which keys it ships on them (М-A5-3, WORK_PLAN 3.11 slice 0).
 *
 * Two inputs, because the client keeps the two halves apart:
 *  - `Interface/FrameXML/Bindings.xml` (the dataset's `luaxml`) lists the 275 commands in the
 *    order and sections the key bindings window shows them — names and attributes only; it has no
 *    key on any `<Binding>` (its sixteen `default=` belong to `<ModifiedClick>`);
 *  - `Data/<locale>/WTF/DefaultBindings.wtf` of the client holds the keys, one `bind <KEY> <COMMAND>`
 *    per line (146 lines in ruRU; `Wow.exe` itself carries no command strings).
 *
 * Only names, flags and key names are written — no Lua bodies, no localised text — so the table is
 * the same kind of fact as the opcode tables and stays tracked.
 *
 *   node tools/generate-stock-bindings.mjs          write the table
 *   node tools/generate-stock-bindings.mjs --check  fail when the tracked table differs
 */

const projectRoot = fileURLToPath(new URL("..", import.meta.url));
const outputPath = join(projectRoot, "src", "generated", "stockBindings.ts");
const checkOnly = process.argv.includes("--check");

/** `<Binding name=… header=…>` attributes, in file order; the header carries over to the rows after it. */
export function parseBindingsXml(xml) {
  const commands = [];
  let header = "";
  for (const match of xml.matchAll(/<Binding\s([^>]*)>/g)) {
    const attributes = Object.fromEntries([...match[1].matchAll(/(\w+)="([^"]*)"/g)].map(([, key, value]) => [key, value]));
    if (!attributes.name) continue;
    if (attributes.header) header = attributes.header;
    commands.push({
      name: attributes.name,
      header,
      runOnUp: attributes.runOnUp === "true",
      hidden: attributes.hidden === "true",
      debug: attributes.debug === "true",
      ...(attributes.platform ? { platform: attributes.platform } : {}),
    });
  }
  return commands;
}

/** `bind <KEY> <COMMAND>` lines: command → keys in file order. Anything else is skipped. */
export function parseDefaultBindings(text) {
  const keys = new Map();
  for (const raw of text.split(/\r?\n/)) {
    const match = /^\s*bind\s+(\S+)\s+(\S+)\s*$/i.exec(raw);
    if (!match) continue;
    const [, key, command] = match;
    if (!keys.has(command)) keys.set(command, []);
    keys.get(command).push(key);
  }
  return keys;
}

function defaultBindingsPath(clientDir) {
  const locale = process.env.CLIENT_LOCALE;
  const data = join(clientDir, "Data");
  const locales = locale ? [locale] : readdirSync(data).filter((name) => /^[a-z]{2}[A-Z]{2}$/.test(name));
  for (const candidate of locales) {
    const path = join(data, candidate, "WTF", "DefaultBindings.wtf");
    if (existsSync(path)) return path;
  }
  throw new Error(`no Data/<locale>/WTF/DefaultBindings.wtf under ${clientDir}`);
}

export function renderStockBindings(commands, keys) {
  const lines = [];
  lines.push("// Generated by tools/generate-stock-bindings.mjs from the dataset's Interface/FrameXML/Bindings.xml");
  lines.push("// (commands, sections, flags) and the client's Data/<locale>/WTF/DefaultBindings.wtf (keys).");
  lines.push("// Do not edit by hand: `node tools/generate-stock-bindings.mjs`, checked with `--check`.");
  lines.push("");
  lines.push("export interface StockBindingCommand {");
  lines.push("  readonly name: string;");
  lines.push("  /** The `HEADER_*` section (without the prefix) the command is listed under. */");
  lines.push("  readonly header: string;");
  lines.push("  readonly runOnUp: boolean;");
  lines.push("  readonly hidden: boolean;");
  lines.push("  readonly debug: boolean;");
  lines.push("  readonly platform?: string;");
  lines.push("}");
  lines.push("");
  lines.push("/** Every `<Binding>` of Bindings.xml, in the file's order. */");
  lines.push("export const STOCK_BINDING_COMMANDS: readonly StockBindingCommand[] = [");
  for (const command of commands) {
    const platform = command.platform ? `, platform: ${JSON.stringify(command.platform)}` : "";
    lines.push(`  { name: ${JSON.stringify(command.name)}, header: ${JSON.stringify(command.header)}, runOnUp: ${command.runOnUp}, hidden: ${command.hidden}, debug: ${command.debug}${platform} },`);
  }
  lines.push("];");
  lines.push("");
  lines.push("/** The keys DefaultBindings.wtf ships on each command, in the client's notation (`CTRL-SHIFT-TAB`). */");
  lines.push("export const STOCK_DEFAULT_KEYS: Readonly<Record<string, readonly string[]>> = {");
  for (const [command, list] of keys) {
    lines.push(`  ${JSON.stringify(command)}: [${list.map((key) => JSON.stringify(key)).join(", ")}],`);
  }
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}

async function main() {
  const [xml, wtf] = await Promise.all([
    readFile(join(interfaceDirectory(), "FrameXML", "Bindings.xml"), "utf8"),
    readFile(defaultBindingsPath(sourceClientDirectory()), "utf8"),
  ]);
  const commands = parseBindingsXml(xml);
  const keys = parseDefaultBindings(wtf);
  if (commands.length === 0 || keys.size === 0) throw new Error("Bindings.xml or DefaultBindings.wtf yielded nothing — the format changed");
  const output = renderStockBindings(commands, keys);
  if (checkOnly) {
    const tracked = existsSync(outputPath) ? await readFile(outputPath, "utf8") : "";
    if (tracked !== output) {
      console.error("src/generated/stockBindings.ts is out of date: run node tools/generate-stock-bindings.mjs");
      process.exitCode = 1;
      return;
    }
    console.log(`stockBindings.ts up to date (${commands.length} commands, ${keys.size} with keys)`);
    return;
  }
  await writeFile(outputPath, output);
  console.log(`wrote ${outputPath}: ${commands.length} commands, ${keys.size} with default keys`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
