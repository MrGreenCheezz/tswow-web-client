// Emits the ignored local src/generated/client-data/animations.ts implementation from
// AnimationData.dbc. The tracked src/generated/animations.ts file is a data-free facade.
//
// The browser has to name animations too — "swim", not 42 — and it cannot open a DBC. Same
// interface as the other generated modules, but this client-derived implementation remains local
// and ignored by Git. `--check` reports drift against the user's configured dataset.

import { readFile, writeFile } from "node:fs/promises";
import { BASE_ANIMATION_NAMES, baseAnimationIds, loadAnimationCatalog, loadEmoteAnimations } from "./animations.mjs";
import { clientDataImplementationPath, ensureClientDataDirectory } from "./client-data.mjs";

const destination = clientDataImplementationPath("animations");
const check = process.argv.includes("--check");

const catalog = await loadAnimationCatalog();
const base = baseAnimationIds(catalog);
const emotes = await loadEmoteAnimations();

const names = [...catalog.nameById.entries()]
  .filter(([, name]) => name)
  .sort((left, right) => left[0] - right[0]);
const fallbacks = [...catalog.fallback.entries()].sort((left, right) => left[0] - right[0]);

const lines = [];
lines.push("// Generated by tools/generate-animations.mjs from AnimationData.dbc. Do not edit by");
lines.push("// hand. This local implementation is ignored by Git and never redistributed.");
lines.push("//");
lines.push(`// ${names.length} named animations, ${fallbacks.length} with a visual equivalent,`);
lines.push(`// ${emotes.length} emotes that name one.`);
lines.push("");
lines.push("export const ANIMATION_DATA_AVAILABLE = true as const;");
lines.push("");
lines.push("/** Animation name to AnimationData.dbc id. The only place a number is attached to a pose. */");
lines.push("export const ANIMATION_IDS = {");
for (const [id, name] of names) lines.push(`  ${JSON.stringify(name)}: ${id},`);
lines.push("} as const;");
lines.push("");
lines.push("export type AnimationName = keyof typeof ANIMATION_IDS;");
lines.push("");
lines.push("/** Id back to name, for diagnostics and for reading a log of what a unit is doing. */");
lines.push("export const ANIMATION_NAMES: Readonly<Record<number, string>> = {");
for (const [id, name] of names) lines.push(`  ${id}: ${JSON.stringify(name)},`);
lines.push("};");
lines.push("");
lines.push("/**");
lines.push(" * AnimationData.Fallback: the pose to try when a model has no sequence of its own.");
lines.push(" *");
lines.push(" * The table calls it the visual equivalent, and it is a chain — Attack2HL gives way to");
lines.push(" * Attack2H, which gives way to Attack1H, which gives way to AttackUnarmed. Walking it is");
lines.push(" * what lets one set of names drive a wolf, a murloc and a night elf.");
lines.push(" */");
lines.push("export const ANIMATION_FALLBACK: Readonly<Record<number, number>> = {");
for (const [id, next] of fallbacks) lines.push(`  ${id}: ${next},`);
lines.push("};");
lines.push("");
lines.push("/**");
lines.push(" * The animations that travel inside the model artifact: standing, moving, dying.");
lines.push(" *");
lines.push(" * Everything else the model carries is published beside it and fetched the first time");
lines.push(" * something asks to play it. See tools/animations.mjs for why the line is drawn here.");
lines.push(" */");
lines.push(`export const BASE_ANIMATIONS: readonly number[] = [${[...base].sort((a, b) => a - b).join(", ")}];`);
lines.push("");
lines.push("/**");
lines.push(" * `SMSG_EMOTE` carries an Emotes.dbc id, and this is the pose it means.");
lines.push(" *");
lines.push(" * `state` is `EmoteSpecProc`: 0 plays once and ends, anything else is a stance the unit");
lines.push(" * holds until it moves — which is why /dance keeps dancing and /wave does not keep waving.");
lines.push(" */");
lines.push("export const EMOTE_ANIMATIONS: Readonly<Record<number, { animation: number; state: boolean }>> = {");
for (const emote of emotes) lines.push(`  ${emote.id}: { animation: ${emote.animation}, state: ${emote.state} },`);
lines.push("};");
lines.push("");
const generated = lines.join("\n") + "\n";

if (check) {
  const current = await readFile(destination, "utf8").catch(() => "");
  if (current.replaceAll("\r\n", "\n") !== generated) {
    throw new Error("The ignored animations implementation is out of date. Run `npm run animations:generate`.");
  }
  console.log(`The ignored animations implementation is current: ${names.length} animations, ${base.size} of them shipped with the model`);
} else {
  ensureClientDataDirectory();
  await writeFile(destination, generated);
  const missing = BASE_ANIMATION_NAMES.filter((name) => !catalog.idByName.has(name));
  if (missing.length > 0) console.warn(`  not in this build's table: ${missing.join(", ")}`);
  console.log(`Generated ignored client-data/animations.ts: ${names.length} animations, `
    + `${fallbacks.length} fallbacks, ${base.size} shipped with the model`);
}
